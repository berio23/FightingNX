"""Writes the census build's hooks: one counting hook for every function in FNC's Direct3D range that has no hook of
its own in the app (app/src/fnc/fnc_d3d_census.cpp counts them; cvar fnc_d3d_census).

    python tools/fnc_d3d_census_build.py [--low 82CD0000] [--high 82D00000]

Writes out/census/fnc_d3d_census_all.cpp. Configure the PC build with
-DSA2_EXTRA_SOURCES=<absolute path of that file>, and with -DSA2_EXTRA_SOURCES= to go back. Classic codegen only: the
optimised flavour's direct calls (tools/direct_calls.py) would call around hooks it does not know about.
"""
import argparse
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, 'app', 'generated', 'default')
OUT = os.path.join(ROOT, 'out', 'census')

ap = argparse.ArgumentParser()
ap.add_argument('--low', default='82C80000')  # wide enough to take in XGRAPHC if it sits just below Direct3D (unverified)
ap.add_argument('--high', default='82D10000')
a = ap.parse_args()
low, high = int(a.low, 16), int(a.high, 16)

funcs = set()
for path in glob.glob(os.path.join(GEN, 'fnc_recomp.*.cpp')):
    for m in re.finditer(r'^DEFINE_REX_FUNC\(sub_([0-9A-F]{8})\)', open(path, errors='replace').read(), re.M):
        if low <= int(m.group(1), 16) < high:
            funcs.add(m.group(1))

# Functions the app already hooks (a second definition would not link).
hook_re = re.compile(r'(?:REX_HOOK_RAW\(sub_|REX_HOOK\(sub_|extern "C" void sub_|BANJO_RENUT_HOOK\w*\(sub_)([0-9A-F]{8})')
hooked = set()
for dirpath, _, files in os.walk(os.path.join(ROOT, 'app', 'src', 'fnc')):
    for name in files:
        if name.endswith(('.cpp', '.h', '.inc')):
            hooked |= set(hook_re.findall(open(os.path.join(dirpath, name), errors='replace').read()))

census = sorted(funcs - hooked)
os.makedirs(OUT, exist_ok=True)
with open(os.path.join(OUT, 'fnc_d3d_census_all.cpp'), 'w', encoding='utf-8', newline='\n') as o:
    o.write('// Generated by tools/fnc_d3d_census_build.py: the census build\'s hooks (diagnostic only, not committed).\n')
    o.write('#include <rex/hook.h>\n#include <rex/ppc.h>\n\n#include "fnc/fnc_d3d_census.h"\n\n')
    o.write('namespace {\nconstexpr uint32_t kAddresses[] = {\n')
    for i in range(0, len(census), 8):
        o.write('    ' + ', '.join(f'0x{x}' for x in census[i:i + 8]) + ',\n')
    o.write('};\nconst bool g_registered = [] {\n'
            '  fnc::census::Register(kAddresses, int(sizeof(kAddresses) / sizeof(kAddresses[0])));\n'
            '  return true;\n}();\n}  // namespace\n\n')
    o.write('#define FNC_CENSUS_HOOK(addr, index)      \\\n'
            '  extern "C" REX_FUNC(__imp__sub_##addr); \\\n'
            '  REX_HOOK_RAW(sub_##addr) {              \\\n'
            '    fnc::census::Note(index, ctx, base);  \\\n'
            '    __imp__sub_##addr(ctx, base);         \\\n'
            '  }\n\n')
    for i, x in enumerate(census):
        o.write(f'FNC_CENSUS_HOOK({x}, {i})\n')
print(f'{len(funcs)} functions in 0x{low:08X}-0x{high:08X}, {len(funcs & hooked)} hooked already, '
      f'{len(census)} census hooks -> {os.path.join(OUT, "fnc_d3d_census_all.cpp")}')
